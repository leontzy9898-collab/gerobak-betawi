  const LANG_KEY = "gb_lang";

  function getLang() {
    const stored = localStorage_safe_get(LANG_KEY);
    if (stored === "id" || stored === "en") return stored;
    const nav = (navigator.language || "id").toLowerCase();
    return nav.startsWith("id") ? "id" : "en";
  }

  function localStorage_safe_get(key) {
    try { return localStorage.getItem(key); } catch (e) { return null; }
  }
  function localStorage_safe_set(key, val) {
    try { localStorage.setItem(key, val); } catch (e) { /* no-op */ }
  }

  function applyLang(lang) {
    const dict = STRINGS[lang] || STRINGS.id;
    document.documentElement.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key] !== undefined) el.textContent = dict[key];
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (dict[key] !== undefined) el.setAttribute("aria-label", dict[key]);
    });

    document.querySelectorAll(".lang-switch button").forEach((btn) => {
      btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
    });

    document.documentElement.setAttribute("data-current-lang", lang);
    window.GB_CURRENT_LANG = lang;
    document.dispatchEvent(new CustomEvent("gb:langchange", { detail: { lang } }));
  }

  function setLang(lang) {
    localStorage_safe_set(LANG_KEY, lang);
    applyLang(lang);
  }

  function initLangSwitchers() {
    document.querySelectorAll(".lang-switch button").forEach((btn) => {
      btn.addEventListener("click", () => setLang(btn.getAttribute("data-lang")));
    });
  }

  document.addEventListener("DOMContentLoaded", () => {
    initLangSwitchers();
    applyLang(getLang());
  });

  window.GB_I18N = { setLang, getLang, STRINGS };
